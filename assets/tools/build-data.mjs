/**
 * Build script — parses AGENTS.md into js/data.js and fetches the Lucide
 * icons used by the UI into js/icons.js.
 *
 *   bun tools/build-data.mjs
 */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const markdown = await readFile(join(root, "AGENTS.md"), "utf8");

const ICONS = {
  // interface
  search: "search",
  close: "x",
  menu: "menu",
  sun: "sun",
  moon: "moon",
  copy: "copy",
  check: "check",
  book: "book-open",
  leaf: "leaf",
  sparkle: "sparkles",
  arrowUp: "arrow-up",
  // chapters
  ch1: "message-circle",
  ch2: "compass",
  ch3: "badge-check",
  ch4: "hand-helping",
  ch5: "send",
  ch6: "calendar-clock",
  ch7: "life-buoy",
  ch8: "graduation-cap",
  ch9: "heart",
  ch10: "briefcase",
  ch11: "handshake",
  ch12: "sun-medium",
  ch13: "smile",
  ch14: "layers",
  ch15: "clipboard-check",
  ch16: "repeat",
};

const lines = markdown.split(/\r?\n/);
const categories = [];
let current = null;

for (const line of lines) {
  const heading = line.match(/^##\s+(\d+)\.\s+(.+?)\s*$/);
  if (heading) {
    const raw = heading[2];
    const bn = raw.match(/\(([^)]+)\)\s*$/)?.[1] ?? "";
    const en = raw.replace(/\s*\([^)]+\)\s*$/, "");
    current = {
      id: `ch-${String(heading[1]).padStart(2, "0")}`,
      number: Number(heading[1]),
      title: en,
      banglaTitle: bn,
      icon: `ch${heading[1]}`,
      phrases: [],
    };
    categories.push(current);
    continue;
  }

  if (!current || !line.startsWith("|")) continue;
  const cells = line.split("|").slice(1, -1).map((c) => c.trim());
  if (cells.length !== 3) continue;
  if (cells[0] === "Phonetic Bangla") continue;
  if (/^-+$/.test(cells[0])) continue;

  current.phrases.push({
    phonetic: cells[0],
    bangla: cells[1],
    english: cells[2],
  });
}

if (!categories.length) throw new Error("No categories parsed from AGENTS.md");

const total = categories.reduce((n, c) => n + c.phrases.length, 0);
const data = `/* Generated by tools/build-data.mjs — edit AGENTS.md instead. */
window.PHRASE_DATA = ${JSON.stringify(categories, null, 2)};
`;
await writeFile(join(root, "js", "data.js"), data, "utf8");

const iconEntries = [];
const missing = [];
for (const [key, name] of Object.entries(ICONS)) {
  const res = await fetch(`https://unpkg.com/lucide-static@1.70.0/icons/${name}.svg`);
  if (!res.ok) {
    missing.push(name);
    continue;
  }
  const svg = await res.text();
  const inner = svg.match(/<svg[^>]*>([\s\S]*?)<\/svg>/)?.[1] ?? "";
  iconEntries.push(`  ${key}: \`${inner.replace(/`/g, "\\`").trim()}\`,`);
}

const iconsFile = `/* Lucide icons (ISC) — generated by tools/build-data.mjs. */
window.ICONS = {
${iconEntries.join("\n")}
};
`;
await writeFile(join(root, "js", "icons.js"), iconsFile, "utf8");

console.log(`categories: ${categories.length}`);
console.log(`phrases:    ${total}`);
if (missing.length) console.log(`missing icons: ${missing.join(", ")}`);
